/* WanderWise service worker: lightweight offline shell for the GitHub Pages app. */
const BASE = new URL("./", self.location).pathname;
const CACHE_NAME = "wanderwise-shell-v5";
const APP_FILES = [
  BASE,
  BASE + "manifest.webmanifest",
  BASE + "js/auth.js",
  BASE + "js/app.js",
  BASE + "js/pwa-register.js",
  BASE + "icons/wanderwise.svg",
  BASE + "offline.html"
];

self.addEventListener("install", event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(APP_FILES))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(
        keys.filter(key => key.startsWith("wanderwise-shell-") && key !== CACHE_NAME)
          .map(key => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", event => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then(response => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then(cache => cache.put(BASE, copy));
          }
          return response;
        })
        .catch(async () => (await caches.match(BASE)) || (await caches.match(BASE + "offline.html")))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(cached => {
      if (cached) return cached;
      return fetch(request).then(response => {
        if (response.ok && response.type === "basic") {
          const copy = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put(request, copy));
        }
        return response;
      });
    })
  );
});
